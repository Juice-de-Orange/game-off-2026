using UnityEngine;

namespace GameOff.Economy
{
    /// <summary>
    /// P132: a cassette, an item of its own kind. One of each (unique), and no goods: no labels, no cargo word, no vendor buys it
    /// (VendorStock.Buys), the drone doesn't take it (TradeWindow), so the market, the barkeeper's wishes, customs and the
    /// Economy Report never see it. It plays its song in a tape deck (CassetteDeck). Built by EconomyBuilder (CassetteBuilder).
    /// </summary>
    [CreateAssetMenu(menuName = "GameOff/Economy/Cassette", fileName = "Item_Cassette_")]
    public class CassetteData : ItemData
    {
        [Tooltip("Title on the label, used in the tape deck's prompts, e.g. \"Night Shift\".")]
        [SerializeField] private string title = "Cassette";
        [Tooltip("The song on it (Audio/Music/MUS_Cassette_0N; MUS_Floppy_01 until that is delivered).")]
        [SerializeField] private AudioClip song;
        [Tooltip("SM_Item_Cassette's material with this cassette's label (generated by the builder); empty = the model's own.")]
        [SerializeField] private Material material;

        public string Title => title;
        public AudioClip Song => song;
        public Material Material => material;

        /// <summary>The first cassette in the inventory (in its order), or null.</summary>
        public static CassetteData FirstIn(Inventory inventory)
        {
            if (inventory == null) return null;
            foreach (var item in inventory.Items)
                if (item is CassetteData cassette) return cassette;
            return null;
        }
    }
}
